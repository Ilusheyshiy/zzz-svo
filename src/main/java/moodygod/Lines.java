    // --- обработка текста ---
    public static List<String> pages(String speech) {
        List<String> out = new ArrayList<>();
        for (String s : speech.split("(?<=[.!?…])\\s+")) {
            s = s.trim();
            if (!s.isEmpty()) out.add(wrap(s, 26));
        }
        return out;
    }

    static String wrap(String s, int w) {
        StringBuilder sb = new StringBuilder();
        int len = 0;
        for (String word : s.split(" ")) {
            if (len > 0 && len + 1 + word.length() > w) { sb.append('\n'); len = 0; }
            else if (len > 0) { sb.append(' '); len++; }
            sb.append(word);
            len += word.length();
        }
        return sb.toString();
    }
